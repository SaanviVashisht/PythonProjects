import random

global month
global distance_travelled
global food_intake
global available_food

total_distance = 2000
available_food = 500
month = 3
DAYS_IN_MONTH=[0,31,28,31,30,31,30,31,31,30,31,30,31]
SICK_COUNT = [0,2,2,2,2,2,2,2,2,2,2,2,2]
miles_min = 30
miles_max = 60
travel_days_min = 3
travel_days_max = 7
rest_days_min = 2
rest_days_max = 5
hunt_days_min = 2
hunt_days_max = 5
distance_travelled = 0
days = 1
health_level = 5
food_intake = 0

commands= ["travel","rest","hunt","status","help","quit"]

def advanceDate():
  global days
  global month
  while(days >= DAYS_IN_MONTH[month]):
    days = days - DAYS_IN_MONTH[month]
    month += 1
  return month, days


def travel():
  global distance_travelled
  global days
  global month
  global food_intake
  distance_travelled += random.randint(miles_min,miles_max)
  d = random.randint(travel_days_min, travel_days_max)
  food_intake += (5*d)
  days+=d
  month, days = advanceDate()
  if(random.random()<0.06):
    fallSick()

def rest():
  global health_level
  global days
  global month
  global food_intake
  if(health_level<5):
    health_level += 1
  d = random.randint(rest_days_min,rest_days_max)
  food_intake += (food_intake*d)
  days+=d
  month, days = advanceDate()
  if(random.random()<0.06):
    fallSick()

def hunt():
  global total_food
  global days
  global month
  global available_food
  global food_intake
  available_food+=100
  d = random.randint(hunt_days_min,hunt_days_max)
  food_intake += (5*d)
  days+=d
  month, days = advanceDate()
  if(random.random()<0.06):
    fallSick()

def status():
  return "Food Intake: "+ str(food_intake), "Available Food: "+str(available_food), "Healh Level: "+str(health_level), "Distance Travelled: "+str(distance_travelled),"Month: "+str(month),  "Days: "+str(days)

def help():
  return commands

def fallSick():
  global health_level
  if(SICK_COUNT[month]>0):
    health_level = health_level-1
    SICK_COUNT[month] = SICK_COUNT[month]-1

def canGameContinue():
  if distance_travelled >= total_distance:
    print("Congragulations you reached Oregon. You won the game !!")
    return False
  elif food_intake >= available_food:
    print("Sorry, no food available. You lost the game !!")
    return False
  elif month==12 and distance_travelled<total_distance:
      print("Sorry, you've exceeded the deadline Dec 31st. You lost the game !!")
      return False
  elif health_level == 0:
    print("Sorry, you are feeling sick. You lost the game !!")
    return False
  else:
    return True

print("Welcome to The Oregon Trail Game")
print("Here are the commands")
print(help())
while(canGameContinue()):
  user_input = input("Please enter the command").lower()
  if(user_input=="travel"):
    travel()
    print(status())
  elif(user_input=="hunt"):
    hunt()
    print(status())
  elif(user_input=="rest"):
    rest()
    print(status())
  elif(user_input=="status"):
    status()
  elif(user_input=="help"):
    print(help())
  elif(user_input=="quit"):
    break
  else:
    print("Please enter a valid command")